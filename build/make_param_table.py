"""Writes docs/PARAMETERS.md from the built device (the source of truth for Live parameter identity)."""
import json, os
ROOT = os.path.join(os.path.dirname(__file__), "..")
p = json.load(open(os.path.join(ROOT, "devices", os.environ.get("HH_DEVICE_NAME", "Echolivity_HH_v0.2.3-dev") + ".maxpat")))["patcher"]
B = {b["box"]["id"]: b["box"] for b in p["boxes"]}
dest = {}
for l in p["lines"]:
    s, d = l["patchline"]["source"][0], l["patchline"]["destination"][0]
    t = B[d].get("text", "")
    if t.startswith("prepend "):
        dest[s] = t.split()[1]
rows = []
for k, v in p["parameters"].items():
    if k == "inherited_shortname":
        continue
    b = B[k]; a = b["saved_attribute_attributes"]["valueof"]
    rng = (", ".join(a["parameter_enum"]) if "parameter_enum" in a else f'{a["parameter_mmin"]} … {a["parameter_mmax"]}')
    eng = dest.get(k, {"tap_button": "tap (via counter)"}.get(b.get("varname"), "hold/drive/tape_stop (pad OR latch)" if b.get("varname", "").endswith(("_mom", "_latch")) else "—"))
    rows.append((a["parameter_longname"], a["parameter_shortname"], b.get("varname"), b["maxclass"], rng, a["parameter_initial"][0], eng))
with open(os.path.join(ROOT, "docs", "PARAMETERS.md"), "w") as f:
    f.write("# Live parameters — Echolivity H&H v0.2.3-dev\n\n")
    f.write("Generated by `build/make_param_table.py` from the built device. Live identifies a Max for Live parameter by its "
            "**long name** (automation, MIDI mappings, presets). All v0.2.1 names are unchanged; v0.2.2-dev adds Slider Taper, "
            "Slider Position, Slider Min and Slider Max. Every parameter is Automated and Stored, so Live's LFO, Shaper, "
            "Envelope Follower and other modulators can map to it.\n\n")
    f.write(f"{len(rows)} parameters.\n\n| # | Long name (ID) | Short | varname | Object | Range | Default | Engine Param |\n|---|---|---|---|---|---|---|---|\n")
    for i, r in enumerate(rows, 1):
        f.write(f"| {i} | {r[0]} | {r[1]} | `{r[2]}` | {r[3]} | {r[4]} | {r[5]} | `{r[6]}` |\n")
print(len(rows), "parameters")
